export const getStockName = (symbol: string): string => {
  const clean = symbol.replace('.NS', '').replace('.BO', '');
  return NSE_STOCKS.find(s => s.symbol === symbol || s.symbol.startsWith(clean))?.name ?? clean;
};

export const getStockSector = (symbol: string): string => {
  return NSE_STOCKS.find(s => s.symbol === symbol)?.sector ?? 'Unknown';
};
